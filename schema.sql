-- ---------------------------------------------------------------------------
--  Table 1 : CURRENCIES
--  One row per supported currency. rate_per_usd = how many units of this
--  currency equal 1 US Dollar. USD itself is therefore exactly 1.
--  New currencies can be supported later by simply INSERTing another row.
-- ---------------------------------------------------------------------------
CREATE TABLE currencies (
    currency_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          CHAR(3)       NOT NULL UNIQUE,
    name          VARCHAR2(50)  NOT NULL,
    symbol        VARCHAR2(8),
    rate_per_usd  NUMBER(18,6)  NOT NULL,
    updated_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT chk_rate_positive CHECK (rate_per_usd > 0)
);

-- ---------------------------------------------------------------------------
--  Table 2 : CONVERSION_HISTORY
--  One row per successful conversion. Rows belong to a browser session,
--  so no login is required and every visitor sees only their own history.
-- ---------------------------------------------------------------------------
CREATE TABLE conversion_history (
    history_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  VARCHAR2(64)  NOT NULL,
    from_code   CHAR(3)       NOT NULL,
    to_code     CHAR(3)       NOT NULL,
    amount      NUMBER(18,4)  NOT NULL,
    converted   NUMBER(18,4)  NOT NULL,
    rate_used   NUMBER(18,6)  NOT NULL,
    created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_hist_from FOREIGN KEY (from_code) REFERENCES currencies (code),
    CONSTRAINT fk_hist_to   FOREIGN KEY (to_code)   REFERENCES currencies (code)
);

-- Makes "newest 5 rows for this visitor" fast.
CREATE INDEX idx_hist_session_time
    ON conversion_history (session_id, created_at DESC);


