-- XEPDB1 is the pluggable database that Oracle XE creates for applications.
-- The SYSTEM account starts off in the container root, so we move into it.
ALTER SESSION SET CONTAINER = XEPDB1;

CREATE USER takabridge IDENTIFIED BY takabridge123;

-- CONNECT lets the user log in; RESOURCE lets it create its own tables.
GRANT CONNECT, RESOURCE TO takabridge;

-- RESOURCE alone grants no storage, so the user needs a quota as well.
ALTER USER takabridge QUOTA UNLIMITED ON USERS;


